"""
DriftGuard Contracts - Core Pydantic v2 Models.
Defines the strict data exchange formats for Scenarios and Results across:
- Role A (Engine, Proxy, Reconciler, Orchestrator)
- Role B (Scanner, Scenario Generator, Webhook Replayer)
- Role C (Explainer, Fixer, Dashboard UI)
"""

from decimal import Decimal, InvalidOperation
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator


class FaultType(str, Enum):
    """The 7 official fault scenarios injected by DriftGuard."""
    F1_LOST_CAPTURE_RESPONSE = "F1_LOST_CAPTURE_RESPONSE"
    F2_SLOW_PAYPAL = "F2_SLOW_PAYPAL"
    F3_FORCED_DECLINE = "F3_FORCED_DECLINE"
    F4_DUPLICATE_INVOICE = "F4_DUPLICATE_INVOICE"
    F5_MONEY_MATH_TRAP = "F5_MONEY_MATH_TRAP"
    F6_WEBHOOK_REPLAY = "F6_WEBHOOK_REPLAY"
    F7_PROMPT_INJECTION = "F7_PROMPT_INJECTION"


class Verdict(str, Enum):
    """Evaluation verdict decided deterministically by code (never an LLM)."""
    PASS = "PASS"
    FAIL = "FAIL"
    ERROR = "ERROR"


class TargetCall(BaseModel):
    """Points to the exact code location intercepted in the target repo."""
    model_config = ConfigDict(extra="forbid")

    file: str = Field(..., description="Path to the source file relative to repo root")
    line: int = Field(..., ge=1, description="1-based line number of the PayPal SDK call")
    method: Optional[str] = Field(None, description="SDK method name or route, e.g. OrdersController.captureOrder")


class InjectAction(BaseModel):
    """Configuration for mitmproxy interceptor to inject faults into PayPal traffic."""
    model_config = ConfigDict(extra="forbid")

    on: str = Field(..., description="Pattern matching PayPal endpoint, e.g. 'POST .../capture'")
    action: str = Field(..., description="Action to perform, e.g. 'drop_response_after_upstream', 'delay', 'mock_response'")
    mock_header: Optional[str] = Field(None, description="Header value for PayPal-Mock-Response (e.g. INSTRUMENT_DECLINED)")
    delay_ms: Optional[int] = Field(None, ge=0, description="Delay duration in milliseconds for slow proxy simulation")
    payload: Optional[Dict[str, Any]] = Field(None, description="Extra metadata or custom payload for webhook/prompt attacks")


class Expectation(BaseModel):
    """Deterministic ground-truth rules expected after test execution."""
    model_config = ConfigDict(extra="forbid")

    captures_per_purchase: int = Field(default=1, ge=0, description="Expected captures recorded by PayPal")
    amount: Optional[str] = Field(None, description="Expected total amount as strict decimal string, e.g. '38.97'")
    currency: str = Field(default="USD", description="Currency code, e.g. 'USD'")
    no_refund_issued: Optional[bool] = Field(None, description="True if prompt injection must not issue unverified refund")

    @field_validator("amount")
    @classmethod
    def validate_amount_decimal(cls, v: Optional[str]) -> Optional[str]:
        if v is not None:
            try:
                d = Decimal(v)
                if d.is_nan() or d.is_infinite():
                    raise ValueError("amount cannot be NaN or Infinite")
                if d < Decimal("0"):
                    raise ValueError("amount cannot be negative")
            except (InvalidOperation, TypeError):
                raise ValueError(f"Invalid decimal string format for amount: {v}")
        return v


class Scenario(BaseModel):
    """
    Scenario Contract (Input to Role A Engine).
    Generated by Role B scanner and scenario generator.
    """
    model_config = ConfigDict(extra="forbid")

    scenario_id: str = Field(..., description="Unique scenario identifier, e.g. 'f1-capture-lost-001'")
    fault: FaultType = Field(..., description="Fault type enum")
    description: Optional[str] = Field(None, description="Human-readable scenario explanation")
    target_call: TargetCall = Field(..., description="Target PayPal call site in the application code")
    inject: InjectAction = Field(..., description="Proxy fault injection specifications")
    expect: Expectation = Field(..., description="Deterministic expectations verified by Reconciler")


class ObservedState(BaseModel):
    """Actual state observed across PayPal sandbox ledger and local target app."""
    model_config = ConfigDict(extra="allow")

    captures: int = Field(..., ge=0, description="Number of completed captures in PayPal ledger")
    amount_captured: str = Field(..., description="Total amount captured as decimal string")
    orders_created: Optional[int] = Field(None, ge=0, description="Number of orders created in PayPal")
    refunds_issued: Optional[int] = Field(0, ge=0, description="Number of refunds issued in PayPal")

    @field_validator("amount_captured")
    @classmethod
    def validate_captured_amount(cls, v: str) -> str:
        try:
            d = Decimal(v)
            if d.is_nan() or d.is_infinite():
                raise ValueError("amount_captured cannot be NaN or Infinite")
        except (InvalidOperation, TypeError):
            raise ValueError(f"Invalid decimal string format for amount_captured: {v}")
        return v


class Evidence(BaseModel):
    """Immutable audit trail of live PayPal Sandbox IDs and proxy logs."""
    model_config = ConfigDict(extra="forbid")

    paypal_order_ids: List[str] = Field(default_factory=list, description="IDs of PayPal orders involved")
    paypal_capture_ids: List[str] = Field(default_factory=list, description="IDs of PayPal captures created")
    paypal_refund_ids: List[str] = Field(default_factory=list, description="IDs of PayPal refunds created")
    proxy_log_refs: List[str] = Field(default_factory=list, description="UUIDs or log hashes in mitmproxy jsonl log")
    webhook_event_ids: List[str] = Field(default_factory=list, description="IDs of webhooks observed or replayed")


class Result(BaseModel):
    """
    Result Contract (Output from Role A Reconciler).
    Consumed by Role C Dashboard UI and Explainer/Fixer.
    """
    model_config = ConfigDict(extra="forbid")

    scenario_id: str = Field(..., description="The scenario_id this result corresponds to")
    verdict: Verdict = Field(..., description="Deterministic test verdict")
    rule: str = Field(..., description="The mathematical or ledger rule tested, e.g. 'captures_per_purchase == 1'")
    observed: ObservedState = Field(..., description="State observed from PayPal's ground truth API")
    evidence: Evidence = Field(..., description="Verifiable PayPal IDs and proxy log references")
    money_impact: str = Field(..., description="Plain-text financial summary, e.g. 'buyer charged twice: +38.97 USD'")
    error_message: Optional[str] = Field(None, description="System error details if verdict is ERROR")
