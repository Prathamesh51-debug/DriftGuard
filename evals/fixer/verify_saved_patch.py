"""Replay an archived Fixer diff against a disposable live Sandbox shop.

This performs no model call. It is for evaluating a patch already generated by
the model-only eval, with the same build and orchestrator path as the product.
"""

import argparse
import hashlib
import json
import time
from pathlib import Path
from unittest.mock import patch

from ai.fixer import check_diff, find_bug, load_bugs
from ai.fixer.fixer import FixProposal
from ai.fixer.verify_run import SHOP, generate_and_verify
from contracts import Result, Scenario


ROOT = Path(__file__).resolve().parents[2]
FIXTURES = ROOT / "contracts" / "fixtures"


def verify(bug_id: str, patch_path: Path) -> dict:
    bug = next(b for b in load_bugs() if b.id == bug_id)
    fault = bug.fault.split("_")[0].lower()
    scenario = Scenario.model_validate_json((FIXTURES / f"{fault}_scenario.json").read_text())
    failing = Result.model_validate_json((FIXTURES / f"{fault}_result_fail.json").read_text())
    if find_bug(scenario, load_bugs()).id != bug_id:
        raise ValueError("This archived patch is not the selected bug for the scenario")
    diff = patch_path.read_text(encoding="utf-8")
    accepted = check_diff(diff, SHOP, bug.file)
    if not accepted.ok:
        raise ValueError(f"Patch acceptance check failed: {accepted.error}")
    proposal = FixProposal(bug_id=bug_id, applies=True, source="llm", provider="anthropic-archived",
                           diff=diff, explanation="Archived model-only evaluation patch",
                           files=accepted.files, lines_changed=accepted.lines_changed,
                           attempts=1, error=None)
    stored = {}
    started = time.monotonic()
    with patch("ai.fixer.verify_run.propose_fix", return_value=proposal):
        result = generate_and_verify(scenario, failing,
                                     lambda accepted_proposal, sha: stored.update(
                                         proposal=accepted_proposal.model_dump(), patch_sha256=sha))
    return {
        "bug_id": bug_id,
        "scenario_id": scenario.scenario_id,
        "patch_path": str(patch_path.relative_to(ROOT)),
        "patch_sha256": hashlib.sha256(diff.encode("utf-8")).hexdigest(),
        "source_sha256": hashlib.sha256((SHOP / bug.file).read_bytes()).hexdigest(),
        "patch_accepted": accepted.ok,
        "elapsed_seconds": round(time.monotonic() - started, 1),
        "applied_patch_sha256": stored["patch_sha256"],
        "result": result.model_dump(mode="json"),
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--bug", required=True)
    parser.add_argument("--patch", required=True, type=Path)
    parser.add_argument("--save", type=Path)
    args = parser.parse_args()
    data = verify(args.bug, args.patch.resolve())
    if args.save:
        args.save.parent.mkdir(parents=True, exist_ok=True)
        args.save.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({key: data[key] for key in
                      ("bug_id", "scenario_id", "patch_sha256", "elapsed_seconds")}, indent=2))
    print("verdict:", data["result"]["verdict"])
    print("observed:", data["result"]["observed"])


if __name__ == "__main__":
    main()
